// A fixed channel name would collide the moment a second caller subscribes
// while the first is still mounted (Supabase throws: "cannot add
// postgres_changes callbacks... after subscribe()") — unlike subscribeLedger,
// this one has more than one simultaneous caller (the Bell, and Settings'
// Manage reminders), so each call needs its own channel.
export function subscribeNotifications(onChange) {
  const ch = supabase
    .channel(`notifications-changes-${Math.random().toString(36).slice(2)}`)
    .on("postgres_changes", { event: "*", schema: "public", table: "notifications" }, onChange)
    .subscribe();
  return () => supabase.removeChannel(ch);
}

/* ---- realtime ---- */
// Postgres filters can't be applied to DELETEs (the old row isn't sent), so this
// stays unfiltered and the caller refetches its own ledger. Cheap at this scale.
export function subscribeLedger(onChange) {
  const ch = supabase
    .channel("ledger-changes")
    .on("postgres_changes", { event: "*", schema: "public", table: "expenses" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "categories" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "ledger_members" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "budgets" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "merchants" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "expense_splits" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "recurring_rules" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "wishlist_goals" }, onChange)
    .on("postgres_changes", { event: "*", schema: "public", table: "notifications" }, onChange)
    .subscribe();
  return () => supabase.removeChannel(ch);
}
